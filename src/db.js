const { Pool } = require("pg");

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL is required");
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.PGSSLMODE === "disable" ? false : { rejectUnauthorized: false },
  max: Number(process.env.PG_POOL_MAX || 10),
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 15000
});

async function query(text, params = []) {
  return pool.query(text, params);
}

async function withTransaction(fn) {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    const result = await fn(client);
    await client.query("COMMIT");
    return result;
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

// Uses the existing Python app's table and column names so the same Neon
// database can be reused without deleting wallet, deposit, or game history.
async function initDb() {
  await query(`
    CREATE TABLE IF NOT EXISTS wallets (
      user_id BIGINT PRIMARY KEY,
      balance_cents INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS bot_users (
      user_id BIGINT PRIMARY KEY,
      full_name TEXT NOT NULL,
      username TEXT,
      registered_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS game_rounds (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      status TEXT NOT NULL,
      opens_at DOUBLE PRECISION NOT NULL,
      closes_at DOUBLE PRECISION NOT NULL,
      numbers_json TEXT NOT NULL DEFAULT '[]',
      drawn_json TEXT NOT NULL DEFAULT '[]',
      next_draw_at DOUBLE PRECISION,
      winner_ticket INTEGER,
      winner_user_id BIGINT,
      finished_at DOUBLE PRECISION,
      created_at TEXT NOT NULL,
      winners_json TEXT NOT NULL DEFAULT '[]',
      prize_cents INTEGER NOT NULL DEFAULT 0,
      house_cents INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS round_tickets (
      round_id BIGINT NOT NULL,
      ticket_no INTEGER NOT NULL,
      user_id BIGINT NOT NULL,
      card_json TEXT NOT NULL,
      created_at TEXT NOT NULL,
      user_name TEXT NOT NULL DEFAULT '',
      PRIMARY KEY (round_id, ticket_no)
    );
    CREATE INDEX IF NOT EXISTS idx_round_tickets_user
      ON round_tickets(round_id, user_id);
    CREATE TABLE IF NOT EXISTS wallet_transactions (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL,
      kind TEXT NOT NULL,
      amount_cents INTEGER NOT NULL,
      description TEXT NOT NULL,
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS deposit_requests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL,
      method TEXT NOT NULL,
      sms_text TEXT NOT NULL,
      sms_hash TEXT NOT NULL UNIQUE,
      status TEXT NOT NULL DEFAULT 'pending',
      amount_cents INTEGER,
      created_at TEXT NOT NULL,
      reviewed_at TEXT,
      requested_amount_cents INTEGER
    );
    CREATE TABLE IF NOT EXISTS deposit_sessions (
      user_id BIGINT PRIMARY KEY,
      method TEXT NOT NULL,
      requested_amount_cents INTEGER,
      updated_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS withdrawal_requests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL,
      method TEXT NOT NULL,
      amount_cents INTEGER NOT NULL,
      account_details TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TEXT NOT NULL,
      reviewed_at TEXT
    );
    CREATE TABLE IF NOT EXISTS tickets (
      ticket_no INTEGER PRIMARY KEY,
      user_id BIGINT NOT NULL,
      card_json TEXT NOT NULL,
      created_at TEXT NOT NULL
    );
  `);
  await query("CREATE TABLE IF NOT EXISTS bot_flow_sessions (user_id BIGINT PRIMARY KEY, state_json TEXT NOT NULL, updated_at TEXT NOT NULL)");
  await query("ALTER TABLE deposit_requests ADD COLUMN IF NOT EXISTS requested_amount_cents INTEGER");
  await query("ALTER TABLE game_rounds ADD COLUMN IF NOT EXISTS winners_json TEXT NOT NULL DEFAULT '[]'");
  await query("ALTER TABLE game_rounds ADD COLUMN IF NOT EXISTS prize_cents INTEGER NOT NULL DEFAULT 0");
  await query("ALTER TABLE game_rounds ADD COLUMN IF NOT EXISTS house_cents INTEGER NOT NULL DEFAULT 0");
  await query("ALTER TABLE round_tickets ADD COLUMN IF NOT EXISTS user_name TEXT NOT NULL DEFAULT ''");
  await query("UPDATE game_rounds SET opens_at=EXTRACT(EPOCH FROM NOW()), closes_at=EXTRACT(EPOCH FROM NOW())+30 WHERE status='open' AND closes_at-opens_at>30");
}

module.exports = { pool, query, withTransaction, initDb };
